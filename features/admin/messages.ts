export type AdminKey = keyof typeof en;

/** Translate an admin text: Mongolian when the site language is Mongolian, otherwise English. */
export function useAdminT() {
  const { lang, locale } = useI18n();
  const messages = lang === "mn" ? mn : en;
  const t = (key: AdminKey, params?: Record<string, string | number>) => {
    const text = messages[key];
    return params ? text.replace(/\{(\w+)\}/g, (_, n) => String(params[n] ?? `{${n}}`)) : text;
  };
  const date = (iso: string | null) => (iso ? new Date(iso).toLocaleString(locale) : "");
  return { t, date };
}
